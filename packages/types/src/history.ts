import { z } from "zod"

/**
 * HistoryItem
 */

export const historyItemSchema = z.object({
	id: z.string(),
	rootTaskId: z.string().optional(),
	parentTaskId: z.string().optional(),
	number: z.number(),
	ts: z.number(),
	task: z.string(),
	tokensIn: z.number(),
	tokensOut: z.number(),
	cacheWrites: z.number().optional(),
	cacheReads: z.number().optional(),
	totalCost: z.number(),
	size: z.number().optional(),
	workspace: z.string().optional(),
	mode: z.string().optional(),
	/** Task profile fixed at creation. Missing means "modes". */
	profile: z.enum(["modes", "cordis"]).optional(),
	/** Plan overlay of a Cordis task. Missing means off. */
	planOverlay: z.boolean().optional(),
	apiConfigName: z.string().optional(), // Provider profile name for sticky profile feature
	status: z.enum(["active", "completed", "delegated"]).optional(),
	delegatedToId: z.string().optional(), // Last child this parent delegated to
	childIds: z.array(z.string()).optional(), // All children spawned by this task
	// Maps the new_task message timestamp to the child task ID it created.
	// Authoritative for subtask links; childIds order is only a legacy fallback.
	newTaskChildLinks: z.record(z.string(), z.string()).optional(),
	awaitingChildId: z.string().optional(), // Child currently awaited (set when delegated)
	completedByChildId: z.string().optional(), // Child that completed and resumed this parent
	completionResultSummary: z.string().optional(), // Summary from completed child
})

export type HistoryItem = z.infer<typeof historyItemSchema>

export const taskProfiles = ["modes", "cordis"] as const
export type TaskProfile = (typeof taskProfiles)[number]
